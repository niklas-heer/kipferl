import { docs } from "fumadocs-mdx:collections/server";
import { type InferPageType, loader } from "fumadocs-core/source";
import { lucideIconsPlugin } from "fumadocs-core/source/lucide-icons";
import { stableVersion } from "@/lib/release";

// See https://fumadocs.dev/docs/headless/source-api for more info
export const source = loader({
  baseUrl: "/docs",
  source: docs.toFumadocsSource(),
  plugins: [lucideIconsPlugin()],
});

export function getPageImage(page: InferPageType<typeof source>) {
  const segments = [...page.slugs, "image.png"];

  return {
    segments,
    url: `/og/docs/${segments.join("/")}`,
  };
}

export async function getLLMText(page: InferPageType<typeof source>) {
  const processed = await page.data.getText("processed");

  return `# ${page.data.title}

Documentation scope: the stable v${stableVersion} release and current source checkout. Homebrew installs v${stableVersion}; older v0.6.0 installations predate the project and package workflows. See /docs/getting-started/installation#stable-release for downloads and /docs/guides/packages#upgrade-to-080 for upgrade notes.

${processed}`;
}
